  if (used.has(i)) continue;
  const item = list[i];
  const body = cleanRaw(item.body);
  if (isGarbage(body, item.title || "")) continue;
  if (rest.some((r) => nearDup(r._raw, body))) continue;

  let title = String(item.title || "ГОРОДСКАЯ ЛЕГЕНДА")
